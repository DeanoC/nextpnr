#!/usr/bin/env python3
"""Generate native Boolean LUT bounds; the public profile selects slow100 only."""
import argparse
import collections
from pathlib import Path
from reference import ROOT, CORNERS, load, sha

PINS = ('A','B','C','D','E','F')


def tables(values):
    grouped = collections.defaultdict(list)
    for r in values:
        kind = r['case'].split('-',1)[1]
        if kind.startswith('carry'): continue
        pin = r['physical'][0]
        key = (int(r['block']=='MLAB'),int(kind.startswith('l6')),r['alm'],r['lane'],PINS.index(pin),CORNERS.index(r['corner']))
        rise = [v for k,v in r['delays_ps'].items() if k[0]=='r']
        fall = [v for k,v in r['delays_ps'].items() if k[0]=='f']
        assert rise and fall
        grouped[key].append((min(v[0] for v in rise),max(v[1] for v in rise),
                             min(v[0] for v in fall),max(v[1] for v in fall)))
    expected=set()
    for block in range(2):
        for mode in range(2):
            for alm in range(10):
                for lane in range(2):
                    pins=range(6) if mode else (0,1,3 if lane else 2,4,5)
                    expected |= {(block,mode,alm,lane,pin,corner) for pin in pins for corner in range(4)}
    assert set(grouped)==expected
    # A direct CELL value is printed to one ps. Round its envelope outward
    # by one ps; do not use a fitted maximum as an early delay.
    return {key:(max(0,min(v[0] for v in rows)-1),max(v[1] for v in rows)+1,
                 max(0,min(v[2] for v in rows)-1),max(v[3] for v in rows)+1)
            for key,rows in grouped.items()}


def header(values):
    data=tables(values)
    bounds=lambda v:'{'+','.join(map(str,v))+'}'
    lines=['// Generated by mistral/tests/lut-carry/lut_model_reference.py; do not edit.',
           '// Fitted native LUT references, not whole-board or silicon signoff.',
           '#pragma once','namespace lut_core_reference {',
           'struct Bounds { int rmin,rmax,fmin,fmax; };',
           'struct Entry { bool valid; Bounds corner[4]; };',
           'inline constexpr const char reference_sha256[] = "'+sha((ROOT/'reference.json.gz').read_bytes())+'";',
           '// block LAB/MLAB, native L5/L6 mode, ALM, half, physical A/B/C/D/E/F.',
           'inline constexpr Entry entries[2][2][10][2][6] = {']
    for block in range(2):
        lines.append(' {')
        for mode in range(2):
            lines.append('  {')
            for alm in range(10):
                lines.append('   {')
                for lane in range(2):
                    entries=[]
                    for pin in range(6):
                        key=(block,mode,alm,lane,pin)
                        valid=(*key,0) in data
                        entries.append('{'+str(valid).lower()+', {'+','.join(bounds(data.get((*key,c),(0,0,0,0))) for c in range(4))+'}}')
                    lines.append('    {'+','.join(entries)+'},')
                lines.append('   },')
            lines.append('  },')
        lines.append(' },')
    lines += ['};','// Unplaced small logical LUTs can occupy either native mode.',
              'inline constexpr Bounds planning[2][6] = {']
    for six in range(2):
        row=[]
        for pin in range(6):
            values=[v for k,v in data.items() if k[4]==pin and k[5]==0 and (not six or k[1]==1)]
            assert values
            row.append(bounds((min(v[0] for v in values),max(v[1] for v in values),min(v[2] for v in values),max(v[3] for v in values))))
        lines.append(' {'+','.join(row)+'},')
    return '\n'.join([*lines,'};','} // namespace lut_core_reference',''])


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=Path,default=ROOT.parent.parent/'lut_core_reference_data.h')
    args=parser.parse_args()
    result=header(load())
    if args.check: assert args.output.read_text()==result,'Generated LUT table is stale'
    else: args.output.write_text(result)
    print('440 complete physical LUT input classes; four corners; public slow100 only')
