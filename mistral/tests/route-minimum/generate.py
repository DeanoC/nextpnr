#!/usr/bin/env python3
"""Check native Quartus observations and emit the bounded slow100 data scale."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parent
TARGET = ROOT.parent.parent / 'lut_route_minimum_data.h'


def generated():
    raw = (ROOT / 'reference.json').read_bytes()
    ref = json.loads(raw)
    assert ref['schema'] == 1 and ref['device'] == '5CSEBA6U23I7'
    assert ref['tool'] == 'Quartus Prime Lite 17.0.2 Build 602'
    assert not ref['physical_or_hardware_acceptance']
    for name, digest in ref['input_sha256'].items():
        assert hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == digest, name
    assert hashlib.sha256(gzip.decompress((ROOT / 'fitted.rbf.gz').read_bytes())).hexdigest() == ref['reference_RBF_sha256']
    native = []
    for line in (ROOT / 'native-scale-observer.log').read_text().splitlines():
        if line.startswith('NATIVE_MODEL_SCALE '):
            row = dict(re.findall(r'(\w+)=([^ ]+)', line))
            native.append(dict(native_model=int(row['model']), pvt=row['pvt'], data_min_scale=float(row['first']),
                clock_min_scale=float(row['second']), additional_max_scale=float(row['third']), mode=int(row['mode'])))
    assert native == ref['rows'] and len(native) == 4
    expected = {f'-{speed}_revprod_1100mv_{temp}c' for speed in ('7', 'm') for temp in ('100', 'n40')}
    assert {r['pvt'] for r in native} == expected
    for row in native:
        assert row['mode'] == 0 and row['native_model'] == (0 if row['pvt'].startswith('-7_') else 1)
        assert 0 < row['data_min_scale'] < row['clock_min_scale'] < row['additional_max_scale'] == 1
    controls = [dict(re.findall(r'(\w+)=([^ ]+)', line))
        for line in (ROOT / 'native-scale-ff-slots.log').read_text().splitlines()
        if line.startswith('NATIVE_MODEL_SCALE ')]
    assert len(controls) == 2 and {r['pvt'] for r in controls} == {r['pvt'] for r in native if r['pvt'].endswith('_100c')}
    for control in controls:
        row = next(r for r in native if r['pvt'] == control['pvt'])
        assert float(control['first']) == row['data_min_scale']
        assert float(control['second']) == row['clock_min_scale']
        assert float(control['third']) == row['additional_max_scale']
    value = next(r['data_min_scale'] for r in native if r['pvt'] == '-7_revprod_1100mv_100c')
    # The observer prints enough digits to round-trip the native float.
    assert abs(struct.unpack('f', struct.pack('f', value))[0] - value) < 5e-10
    digest = hashlib.sha256(raw).hexdigest()
    return '\n'.join(['// Generated by mistral/tests/route-minimum/generate.py; do not edit.',
        '#ifndef NEXTPNR_MISTRAL_LUT_ROUTE_MINIMUM_DATA_H', '#define NEXTPNR_MISTRAL_LUT_ROUTE_MINIMUM_DATA_H',
        'NEXTPNR_NAMESPACE_BEGIN', 'namespace lut_route_minimum {',
        f'inline constexpr double slow100_data_scale = double({value:.9g}f);',
        f'inline constexpr char reference_sha256[] = "{digest}";',
        '} // namespace lut_route_minimum', 'NEXTPNR_NAMESPACE_END', '#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generated()
    if args.check:
        assert TARGET.read_text() == output
    else:
        TARGET.write_text(output)
    print('PASS: four native PVT records, retained inputs/RBF and generated slow100 data scale')
