#!/usr/bin/env python3
"""Generate native GPIO tables; the public profile uses only slow100 data."""
import argparse
from pathlib import Path
from reference import ROOT, SETTINGS, clock_envelopes, envelopes, load, require

MUX_FIELDS = {f'INPUT_REG{i}_SEL' for i in range(5)} | {
    'OUTREG_OUTPUT_SEL', 'OUTREG_MODE_SEL', 'OEREG_OUTPUT_SEL'}
RAM_FIELDS = set(SETTINGS[:5])


def triple(identity):
    parts = identity.split('.')
    require(len(parts) == 4, 'Invalid routing coordinate')
    return '{'+','.join(str(int(v)) for v in parts[1:])+'}'


def header(manifest, data):
    arcs, clocks = envelopes(data), clock_envelopes(data)
    lines = ['// Generated by mistral/tests/gpio-core/model_reference.py; do not edit.',
             '// Fitted native GPIO references, not whole-board or hardware qualification.',
             '#pragma once', '#include "cyclonev.h"', 'namespace gpio_core_reference {',
             'using CV = mistral::CycloneV;',
             'struct Bounds { int a,b,c,d; }; // setup/hold or early/late rise/fall',
             'struct Coordinate { int x,y,index; };',
             'struct Field { CV::bmux_type_t name; int type; };',
             'inline constexpr Field fields[] = {']
    for field in SETTINGS:
        kind = 'MUX' if field in MUX_FIELDS else 'RAM' if field in RAM_FIELDS else 'BOOL'
        lines.append('    {CV::'+field+', CV::MT_'+kind+'},')
    lines.extend(['};', 'struct Site {', '    const char *pin; int x,y,bi; unsigned valid;',
                  '    int settings['+str(len(SETTINGS))+'];',
                  '    Coordinate cuts[5]; // I,OE,Q,CLKOUT,CLKIN',
                  '    Bounds arcs[4][3], clocks[4][3]; // corners x I/OE/Q', '};',
                  'inline constexpr const char reference_sha256[] = "'+manifest['reference_gzip_sha256']+'";',
                  'inline constexpr Site sites[] = {'])
    def bounds(values):
        return '{'+','.join(map(str, (values or [])+[0]*(4-len(values or []))))+'}'
    for pin, corners in arcs.items():
        cfg = data['configuration'][pin]
        values = cfg['values']
        valid = sum(1 << i for i, r in enumerate(corners[0]) if r is not None)
        selectors = ['CV::'+values[f] if f in MUX_FIELDS else values[f] for f in SETTINGS]
        cuts = [values[n] for n in ('DATAOUT0','OEIN0','DATAIN3','CLKOUT0','CLKIN0')]
        lines.append('    {"'+pin+'", '+','.join(str(cfg[k]) for k in ('x','y','bi'))+', '+str(valid)+',')
        lines.append('     {'+','.join(selectors)+'}, {'+','.join(triple(c) for c in cuts)+'},')
        lines.append('     {'+','.join('{'+','.join(bounds(r) for r in c)+'}' for c in corners)+'},')
        lines.append('     {'+','.join('{'+','.join(bounds(r) for r in c)+'}' for c in clocks[pin])+'}},')
    return '\n'.join([*lines, '};', '} // namespace gpio_core_reference', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--config-reader', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT.parent.parent/'gpio_core_reference_data.h')
    args = parser.parse_args()
    manifest, data = load(reader=args.config_reader)
    text = header(manifest, data)
    if args.check:
        require(args.output.read_text() == text, 'Generated GPIO table is stale')
    else:
        args.output.write_text(text)
    print(len(envelopes(data)), 'physical GPIO sites; generated native arcs and clock prefixes')
